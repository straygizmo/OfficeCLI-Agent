import type { HostApp, UiLocale } from "@officecli-agent/protocol";

/**
 * UI language. The add-in passes the Office UI language as `?lang=`; in a browser we fall back
 * to navigator.language. Japanese environments get Japanese, everything else gets English.
 */
function detectLocale(): UiLocale {
  const fromQuery = new URLSearchParams(window.location.search).get("lang");
  const lang = fromQuery || navigator.languages?.[0] || navigator.language || "";
  return lang.toLowerCase().startsWith("ja") ? "ja" : "en";
}

export const locale: UiLocale = detectLocale();
document.documentElement.lang = locale;

